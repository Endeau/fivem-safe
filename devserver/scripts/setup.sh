#!/bin/sh
# Installs ESX Legacy the way the official txAdmin recipe does
# (github.com/esx-framework/esx-recipes, branch legacy), then writes server.cfg.
# Downloads happen once; server.cfg is rewritten on every run so .env changes apply.
set -eu

: "${LICENSE_KEY:?LICENSE_KEY is empty in .env}"
: "${DB_PASSWORD:?DB_PASSWORD is empty in .env}"

apk add --no-cache git curl unzip mariadb-client lua5.4 >/dev/null

DATA=/srv/data
RES="$DATA/resources"
TMP="$DATA/.tmp"
mkdir -p "$RES" "$TMP"

clone() { # repo ref dest
  [ -d "$3" ] && return 0
  git clone --quiet --depth 1 --branch "$2" "https://github.com/$1" "$3"
}

release_zip() { # repo dest_dir
  name=$(basename "$1")
  [ -d "$2/$name" ] && return 0
  curl -fsSL -o "$TMP/$name.zip" "https://github.com/$1/releases/latest/download/$name.zip"
  unzip -q -o "$TMP/$name.zip" -d "$2"
}

if [ ! -d "$RES/[core]" ]; then
  echo "Downloading ESX Legacy..."
  clone citizenfx/cfx-server-data master "$TMP/cfx"
  cp -r "$TMP/cfx/resources" "$RES/[cfx-default]"
  rm -rf "$RES/[cfx-default]/[gameplay]/chat"

  clone esx-framework/esx_core main "$TMP/core"
  clone esx-framework/esx-legacy-addons main "$TMP/addons"
  cp -r "$TMP/core/[core]" "$RES/[core]"
  cp -r "$TMP/addons/[esx_addons]" "$RES/[esx_addons]"

  mkdir -p "$RES/[standalone]"
  clone Bob74/bob74_ipl master "$RES/[standalone]/bob74_ipl"
  release_zip overextended/oxmysql "$RES/[standalone]"
  release_zip overextended/ox_lib "$RES/[standalone]"

  echo "Importing the ESX database..."
  mariadb -h db -u esx -p"$DB_PASSWORD" esx_legacy < "$TMP/core/[SQL]/legacy.sql"
  rm -rf "$TMP"
fi

# Probe and fixed copies of the ESX resources that /se_esx switches between.
lua5.4 /scripts/make-variants.lua /devresources/esx_source_check/fixes.lua "$RES"

# ESX debug mode, driven by the ESX_DEBUG env var. When true, esx_multicharacter
# lets a second client with the same identifier join, so the police repro can be
# run with two clients from one Rockstar account (FiveM -cl2). Rewritten every
# deploy, so flipping the CI variable back to false restores the normal check.
esx_debug=false; [ "${ESX_DEBUG:-false}" = "true" ] && esx_debug=true
esx_cfg="$RES/[core]/es_extended/shared/config/main.lua"
if [ -f "$esx_cfg" ]; then
  sed -i "s/^Config.EnableDebug = .* -- Use Debug options?/Config.EnableDebug = $esx_debug -- Use Debug options?/" "$esx_cfg"
  echo "es_extended Config.EnableDebug = $esx_debug"
fi

cat > "$DATA/server.cfg" <<EOF
# Generated by devserver/scripts/setup.sh, edit .env and rerun setup instead.
endpoint_add_tcp "0.0.0.0:30120"
endpoint_add_udp "0.0.0.0:30120"

sv_licenseKey "$LICENSE_KEY"
sv_hostname "fivem-safe dev"
sv_maxclients 4
sv_master1 ""                # not listed in the server browser
set onesync on
sv_enforceGameBuild 3258
set resources_useSystemChat true
set mysql_connection_string "mysql://esx:$DB_PASSWORD@db/esx_legacy?charset=utf8mb4"
setr esx:locale "fr"

# Security convars from the ESX recipe
sv_enableNetworkedSounds false
sv_enableNetworkedScriptEntityStates false
sv_enableNetworkedPhoneExplosions false
sv_filterRequestControl 2

add_principal group.admin group.user
add_ace group.admin command allow
add_ace group.admin command.quit deny
add_ace resource.es_extended command.add_ace allow
add_ace resource.es_extended command.add_principal allow
add_ace resource.es_extended command.remove_principal allow
add_ace resource.es_extended command.stop allow
# esx_source_check restarts the ESX resources it patches for the before/after test
add_ace resource.esx_source_check command.restart allow
add_ace resource.esx_source_check command.stop allow
add_ace resource.esx_source_check command.start allow

set dev_whitelist:allowed "${ALLOWED_IDENTIFIERS:-}"
set dev_whitelist:open "${OPEN:-false}"   # "true" = laisse entrer tout le monde, le temps d'un test
set safe_events:mode "enforce"
set safe_events:esxPlayer "static"   # the light ESX lookup, validated in game by /se_all
set safe_events:webhook "${DISCORD_WEBHOOK:-}"
set safe_events_demo:allowModeSwitch "true"   # dev server only: lets /se_all test the audit mode

ensure dev_whitelist
ensure chat
ensure oxmysql
ensure ox_lib
ensure esx_lib
ensure es_extended
ensure [core]
ensure [standalone]
ensure [esx_addons]

ensure safe_events
ensure safe_events_demo
ensure esx_source_check
EOF

# Optional extra resources: a compose override can mount them in /private.
for res in /private/*/; do
  [ -f "${res}fxmanifest.lua" ] && echo "ensure $(basename "$res")" >> "$DATA/server.cfg"
done

echo "Done. Start the server with: docker compose up -d fxserver"
